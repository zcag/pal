#!/usr/bin/env node
/**
 * Generate one Raycast command per pal palette.
 *
 * Raycast can't discover commands at runtime - they're declared in
 * package.json and each needs an entry file. So read `pal meta` and write both.
 * That's what turns a palette into a real root-search keyword with its own
 * hotkey, instead of something buried two levels down.
 *
 *   node scripts/sync-commands.mjs                    # all palettes, disabled
 *   node scripts/sync-commands.mjs --enable otp,tabs  # ...with these enabled
 *   node scripts/sync-commands.mjs --only otp,tabs    # only these
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, readdirSync, unlinkSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "src");
const PREFIX = "palette-";

function arg(name) {
  const index = process.argv.indexOf(`--${name}`);
  if (index === -1) return undefined;
  return process.argv[index + 1];
}

const enabled = new Set((arg("enable") ?? "").split(",").map((s) => s.trim()).filter(Boolean));
const only = (arg("only") ?? "").split(",").map((s) => s.trim()).filter(Boolean);

const shellPath = execFileSync(process.env.SHELL || "/bin/zsh", ["-lc", 'printf %s "$PATH"'], {
  encoding: "utf8",
  env: { ...process.env, TERM: "dumb" },
}).trim();

const meta = JSON.parse(
  execFileSync("pal", ["meta"], { encoding: "utf8", env: { ...process.env, PATH: shellPath } }),
);

const palettes = meta.palettes.filter((p) => (only.length ? only.includes(p.name) : true));

// A palette name has to survive becoming a filename and a command name.
const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const titleCase = (name) =>
  name.replace(/[-_]/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());

// Drop previously generated entry files so removed palettes don't linger.
for (const file of readdirSync(srcDir)) {
  if (file.startsWith(PREFIX) && file.endsWith(".tsx")) unlinkSync(join(srcDir, file));
}

const commands = [];
for (const palette of palettes) {
  const name = `${PREFIX}${slug(palette.name)}`;
  writeFileSync(
    join(srcDir, `${name}.tsx`),
    `// Generated by scripts/sync-commands.mjs - do not edit.\n` +
      `import { PaletteView } from "./components/PaletteView";\n\n` +
      `export default function Command() {\n` +
      `  return <PaletteView palette=${JSON.stringify(palette.name)} />;\n` +
      `}\n`,
  );

  const command = {
    name,
    title: titleCase(palette.name),
    subtitle: "Pal",
    description: palette.desc || `Run the ${palette.name} palette`,
    mode: "view",
  };
  if (!enabled.has(palette.name)) command.disabledByDefault = true;
  if (palette.name !== slug(palette.name)) command.keywords = [palette.name];
  commands.push(command);
}

const pkgPath = join(root, "package.json");
const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
// Keep every hand-written command; only the generated palette-* set is ours.
const kept = pkg.commands.filter((c) => !c.name.startsWith(PREFIX));
pkg.commands = [...kept, ...commands.sort((a, b) => a.name.localeCompare(b.name))];
writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);

console.log(
  `wrote ${commands.length} palette commands (${enabled.size} enabled by default)`,
);
